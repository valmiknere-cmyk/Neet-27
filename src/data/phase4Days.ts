import { DaySchedule, PracticePaperInfo } from '../types';

export function createDayP4(
  dayNum: number,
  paperNum: number,
  paperTitle: string,
  paperFocus: string,
  pTopic: string,
  pConcept: string,
  pPractice: string,
  pMcqs: number,
  cTopic: string,
  cConcept: string,
  cPractice: string,
  cMcqs: number,
  bTopic: string,
  bConcept: string,
  bPractice: string,
  bMcqs: number,
  revTask: string,
  errFocus: string,
  ncertRev: string,
  isMilestone: boolean = true,
  milestoneTitle?: string
): DaySchedule {
  const week = Math.ceil(dayNum / 7);
  const month = Math.ceil(dayNum / 30);
  const totalTarget = pMcqs + cMcqs + bMcqs;
  const pyqCount = Math.round(totalTarget * 0.4);

  const practicePaper: PracticePaperInfo = {
    paperNumber: paperNum,
    title: paperTitle,
    totalMarks: 720,
    duration: '3 Hours 20 Minutes (2:00 PM – 5:20 PM)',
    focus: paperFocus,
    analysisTask: `2-Hour Forensic Paper Analysis: Mark all incorrect/unattempted questions, classify errors (concept, calculation, misread), and update Error Book with full solutions.`,
  };

  return {
    dayNumber: dayNum,
    dayLabel: `DAY ${dayNum}`,
    phase: 4,
    phaseTitle: 'Phase 4: 20 Full-Length NEET Practice Papers Marathon',
    month,
    week,
    isMilestoneDay: isMilestone,
    milestoneTitle: milestoneTitle || `MARATHON PAPER ${paperNum} / 20 (720 Marks)`,
    physics: {
      topic: pTopic,
      subtopics: pTopic.split(';').map((s) => s.trim()),
      classConcept: pConcept,
      practice: pPractice,
      mcqCount: pMcqs,
    },
    chemistry: {
      topic: cTopic,
      subtopics: cTopic.split(';').map((s) => s.trim()),
      classConcept: cConcept,
      practice: cPractice,
      mcqCount: cMcqs,
    },
    biology: {
      topic: bTopic,
      subtopics: bTopic.split(';').map((s) => s.trim()),
      classConcept: bConcept,
      practice: bPractice,
      mcqCount: bMcqs,
    },
    mcqPyqTarget: {
      totalTarget,
      pyqCount,
      breakdown: `P: ${pMcqs} | C: ${cMcqs} | B: ${bMcqs} (+ Full 180-Question Mock Exam = ${totalTarget + 180} Questions Today)`,
    },
    revisionTask: {
      primaryTask: revTask,
      errorBookFocus: errFocus,
      ncertRevision: ncertRev,
      testSession: `Full-Length Practice Paper ${paperNum} (720 Marks) from 2:00 PM to 5:20 PM`,
    },
    practicePaper,
  };
}

