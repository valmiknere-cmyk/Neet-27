import { DaySchedule } from '../types';

// Helper to generate day schedules
export function createDay(
  dayNum: number,
  pTopic: string,
  pConcept: string,
  pPractice: string,
  pMcqs: number,
  cTopic: string,
  cConcept: string,
  cPractice: string,
  cMcqs: number,
  bTopic: string,
  bConcept: string,
  bPractice: string,
  bMcqs: number,
  revTask: string,
  errFocus: string,
  ncertRev: string,
  isMilestone: boolean = false,
  milestoneTitle?: string
): DaySchedule {
  const week = Math.ceil(dayNum / 7);
  const month = Math.ceil(dayNum / 30);
  const totalTarget = pMcqs + cMcqs + bMcqs;
  const pyqCount = Math.round(totalTarget * 0.3);

  return {
    dayNumber: dayNum,
    dayLabel: `DAY ${dayNum}`,
    phase: 1,
    phaseTitle: 'Phase 1: Complete Class 11 Syllabus Mastery',
    month,
    week,
    isMilestoneDay: isMilestone,
    milestoneTitle,
    physics: {
      topic: pTopic,
      subtopics: pTopic.split(';').map((s) => s.trim()),
      classConcept: pConcept,
      practice: pPractice,
      mcqCount: pMcqs,
    },
    chemistry: {
      topic: cTopic,
      subtopics: cTopic.split(';').map((s) => s.trim()),
      classConcept: cConcept,
      practice: cPractice,
      mcqCount: cMcqs,
    },
    biology: {
      topic: bTopic,
      subtopics: bTopic.split(';').map((s) => s.trim()),
      classConcept: bConcept,
      practice: bPractice,
      mcqCount: bMcqs,
    },
    mcqPyqTarget: {
      totalTarget,
      pyqCount,
      breakdown: `P: ${pMcqs} | C: ${cMcqs} | B: ${bMcqs} (incl. ~${pyqCount} PYQs)`,
    },
    revisionTask: {
      primaryTask: revTask,
      errorBookFocus: errFocus,
      ncertRevision: ncertRev,
      testSession: isMilestone ? (milestoneTitle || `Week ${week} Cumulative Review Test`) : undefined,
    },
  };
}

